// TestGetByClient проверяет получение посылок по идентификатору клиента
func TestGetByClient(t *testing.T) {
	// prepare
	db, err := sql.Open("sqlite", "tracker.db") // настройте подключение к БД
	require.NoError(t, err)
	defer db.Close()

	parcels := []Parcel{
		getTestParcel(),
		getTestParcel(),
		getTestParcel(),
	}
	parcelMap := map[int]Parcel{}

	// задаём всем посылкам один и тот же идентификатор клиента
	client := randRange.Intn(10_000_000)
	parcels[0].Client = client
	parcels[1].Client = client
	parcels[2].Client = client

	// add
	// добавьте новую посылку в БД, убедитесь в отсутствии ошибки и наличии идентификатора
	for i := 0; i < len(parcels); i++ {
		res, err := db.Exec("insert  into  parcel (client, status, address, created_at) values (:client, :status, :address, :created_at)",
			sql.Named("client", parcels[i].Client),
			sql.Named("status", parcels[i].Status),
			sql.Named("address", parcels[i].Address),
			sql.Named("created_at", parcels[i].CreatedAt))

		require.NoError(t, err)

		id64, err := res.LastInsertId()
		require.NoError(t, err)

		id := int(id64)

		// обновляем идентификатор добавленной у посылки
		parcels[i].Number = id

		// сохраняем добавленную посылку в структуру map, чтобы её можно было легко достать по идентификатору посылки
		parcelMap[id] = parcels[i]
	}

	store := NewParcelStore(db)

	storedParcels, err := store.GetByClient(client)
	require.NoError(t, err)
	require.Len(t, storedParcels, len(parcelMap))

	// check
	for _, parcel := range storedParcels {
		require.Equal(t, parcelMap[parcel.Number].Number, parcel.Number)
		require.Equal(t, parcelMap[parcel.Number].Client, parcel.Client)
		require.Equal(t, parcelMap[parcel.Number].Status, parcel.Status)
		require.Equal(t, parcelMap[parcel.Number].Address, parcel.Address)
		require.Equal(t, parcelMap[parcel.Number].CreatedAt, parcel.CreatedAt)
	}
}
